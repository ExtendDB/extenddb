/// Fold a string under Unicode full case folding, matching the service's
/// resolution of condition key names and tag keys. ASCII letters fold to
/// ASCII lowercase; a non-ASCII code point folds per [`CASE_FOLD`] or to
/// itself.
#[must_use]
pub fn case_fold(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        let cp = c as u32;
        match CASE_FOLD.binary_search_by(|&(k, _)| k.cmp(&cp)) {
            Ok(i) => out.push_str(CASE_FOLD[i].1),
            Err(_) => out.push(c),
        }
    }
    out
}

/// Whether two strings are equal under Unicode full case folding.
#[must_use]
pub fn eq_fold(a: &str, b: &str) -> bool {
    case_fold(a) == case_fold(b)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn table_sorted_and_unique() {
        for w in CASE_FOLD.windows(2) {
            assert!(
                w[0].0 < w[1].0,
                "table must be sorted and unique by code point"
            );
        }
    }

    #[test]
    fn spot_checks() {
        // Single-character folds.
        assert_eq!(case_fold("\u{017f}"), "s"); // long s
        assert_eq!(case_fold("\u{212a}"), "k"); // Kelvin sign
        assert_eq!(case_fold("A"), "a");
        // Multi-character expansions.
        assert_eq!(case_fold("\u{00df}"), "ss"); // sharp s
        assert_eq!(case_fold("\u{1e9e}"), "ss"); // capital sharp s
        assert_eq!(case_fold("\u{fb05}"), "st"); // st ligature
        // Greek final sigma folds to the same as sigma.
        assert_eq!(case_fold("\u{03c2}"), case_fold("\u{03c3}"));
        assert_eq!(case_fold("\u{03a3}"), case_fold("\u{03c3}"));
        // Cherokee folds to another Cherokee code point (a non-ASCII target).
        assert_eq!(case_fold("\u{13f8}"), "\u{13f0}");
        // Code points that must be absent from the table (fold to self).
        assert_eq!(case_fold("\u{0131}"), "\u{0131}"); // dotless i
        // Dotted I folds to 'i' plus a combining dot, not plain 'i'.
        assert_eq!(case_fold("\u{0130}"), "i\u{0307}");
    }
}
